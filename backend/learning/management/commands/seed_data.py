class Command(BaseCommand):
    help = "Заполняет базу буквами грузинского алфавита, категориями и словами"

    @transaction.atomic
    def handle(self, *args, **options):
        translit_map = {}
        for order, (char, ru, name, group) in enumerate(LETTERS):
            letter, _ = GeorgianLetter.objects.update_or_create(
                char=char,
                defaults={"ru_translit": ru, "name": name, "group": group, "order": order},
            )
            translit_map[char] = ru
        self.stdout.write(self.style.SUCCESS(f"Букв: {len(LETTERS)}"))

        categories = {}
        for order, (slug, name, _) in enumerate(CATEGORIES):
            cat, _ = Category.objects.update_or_create(
                slug=slug, defaults={"name": name, "order": order}
            )
            categories[slug] = cat
        self.stdout.write(self.style.SUCCESS(f"Категорий: {len(CATEGORIES)}"))

        total_words = 0
        for slug, words in WORDS.items():
            category = categories[slug]
            for georgian_text, translation in words:
                ru_translit = "".join(translit_map.get(ch, ch) for ch in georgian_text)
                Word.objects.update_or_create(
                    georgian_text=georgian_text,
                    defaults={
                        "ru_translit": ru_translit,
                        "translation_ru": translation,
                        "category": category,
                        "level": "advanced" if georgian_text in ADVANCED_WORDS else "basic",
                    },
                )
                total_words += 1
        self.stdout.write(self.style.SUCCESS(f"Слов: {total_words}"))

        current_texts = {gt for words in WORDS.values() for gt, _ in words}
        deleted, _ = Word.objects.exclude(georgian_text__in=current_texts).delete()
        if deleted:
            self.stdout.write(self.style.WARNING(f"Удалено устаревших слов: {deleted}"))
